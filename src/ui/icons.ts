export type IconName = keyof typeof PATHS;

const SVG_NS = 'http://www.w3.org/2000/svg';

export function icon(name: IconName, size = 20): SVGSVGElement {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.classList.add('subdeck-icon');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', PATHS[name]);
  path.setAttribute('fill', 'currentColor');
  svg.appendChild(path);
  return svg;
}

/** Fills every `<span data-icon="name">` placeholder in static HTML (e.g. the popup) with its SVG. */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => {
    const name = el.dataset.icon as IconName;
    if (name in PATHS) el.replaceChildren(icon(name, Number(el.dataset.size) || 18));
  });
}

/** An icon-only button with an accessible label (also shown as a tooltip). */
export function iconButton(name: IconName, label: string, className: string, size = 20): HTMLButtonElement {
  const btn = document.createElement('button');
  btn.type = 'button';
  btn.className = `subdeck-icon-btn ${className}`;
  btn.setAttribute('aria-label', label);
  btn.title = label;
  btn.appendChild(icon(name, size));
  return btn;
}
